import type { RedirectEvent, RedirectRecord } from '../../shared/types/redirect';

// Plain-text chain summary for the clipboard. Intentionally English (see i18n notes).

const FOOTER = 'Generated by: Redirect Inspector (301.st)';

// URLs are printed verbatim — a trailing slash or a #fragment can be the very
// difference the user is debugging, so the export must not "prettify" them.
function formatUrlForExport(raw: string | undefined): string {
  return raw || 'Unknown URL';
}

function getHost(raw: string | undefined): string {
  try {
    return new URL(raw!).host;
  } catch {
    return '';
  }
}

function isClientStep(step: RedirectEvent): boolean {
  return step.method === 'CLIENT' || step.type === 'client-redirect' || step.statusCode === 'JS';
}

function squashClientNoise(events: RedirectEvent[]): RedirectEvent[] {
  if (!Array.isArray(events) || events.length === 0) return events;

  const result: RedirectEvent[] = [];
  const knownHosts = new Set(
    events
      .map((e) => e.to || e.from)
      .filter(Boolean)
      .map((u) => getHost(u))
      .filter(Boolean),
  );

  for (let i = 0; i < events.length; i++) {
    const step = events[i];
    const next = events[i + 1];

    let drop = false;

    if (isClientStep(step)) {
      const targetHost = getHost(step.to || step.from);
      const nextIsNormal = next && !isClientStep(next);

      if (targetHost && knownHosts.has(targetHost) && nextIsNormal) {
        drop = true;
      }
    }

    if (!drop) {
      result.push(step);
    }
  }

  return result;
}

export function formatRedirectChainForExport(record: RedirectRecord): string {
  if (record?.pending) {
    return ['Redirect chain is still in progress.', '', FOOTER].join('\n');
  }

  const events = squashClientNoise(Array.isArray(record?.events) ? record.events : []);

  const lines = ['Redirect chain:'];

  if (events.length === 0) {
    lines.push('No steps recorded.');
  } else {
    events.forEach((step, index) => {
      const status = step.statusCode ?? '—';
      lines.push(`${index + 1}. ${status} → ${formatUrlForExport(step.to || step.from)}`);
    });
  }

  const finalUrl = record?.finalUrl || events.at(-1)?.to || events.at(-1)?.from || record?.initialUrl;

  if (finalUrl) {
    lines.push('', `Final URL: ${formatUrlForExport(finalUrl)}`);
  }

  const landing = record?.clientLanding;
  if (landing) {
    const note = landing.redacted
      ? 'changed client-side, no server request; sensitive values redacted'
      : 'changed client-side, no server request';
    lines.push(`Address bar: ${landing.url} (${note})`);
  }

  lines.push('', FOOTER);

  return lines.join('\n');
}
